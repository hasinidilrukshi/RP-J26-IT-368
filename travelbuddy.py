elevation = np.random.uniform(5.0, 2200.0, n_samples)

# Ground Truth Hazard Rule (Simulating flash floods, heavy mist, or landslide triggers)
# Severe rain (>50mm), or high rain combined with high elevation/humidity triggers hazards
