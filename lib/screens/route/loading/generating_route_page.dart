import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'dart:convert';
import 'package:http/http.dart' as http;
import '../plan/final_plan_page.dart';
import '../../../services/gemini_service.dart';

class GeneratingRoutePage extends StatefulWidget {
  final Map<String, dynamic> requestData;

  const GeneratingRoutePage({super.key, required this.requestData});

  @override
  State<GeneratingRoutePage> createState() => _GeneratingRoutePageState();
}

class _GeneratingRoutePageState extends State<GeneratingRoutePage> with SingleTickerProviderStateMixin {
  late AnimationController _controller;
  late Animation<double> _scaleAnimation;
  late Animation<double> _fadeAnimation;
  
  String _currentMessage = 'Connecting to TravelBuddy AI...';
  
  @override
  void initState() {
    super.initState();
    
    // Setup animations
    _controller = AnimationController(
      vsync: this,
      duration: const Duration(seconds: 2),
    )..repeat(reverse: true);
    
    _scaleAnimation = Tween<double>(begin: 0.95, end: 1.05).animate(
      CurvedAnimation(parent: _controller, curve: Curves.easeInOut),
    );
    
    _fadeAnimation = Tween<double>(begin: 0.5, end: 1.0).animate(
      CurvedAnimation(parent: _controller, curve: Curves.easeInOut),
    );

    // Call the real backend API
    _generateRealRoute();
  }

  Future<void> _generateRealRoute() async {
    try {
      setState(() { _currentMessage = 'Analyzing your preferences...'; });
      
      // We use 10.0.2.2 because it is the localhost address for the Android Emulator
      final response = await http.post(
        Uri.parse('http://10.0.2.2:8000/api/generate-route'),
        headers: {'Content-Type': 'application/json'},
        body: json.encode(widget.requestData),
      );

      if (!mounted) return;

      if (response.statusCode == 200) {
        final data = json.decode(response.body);
        
        setState(() { _currentMessage = 'TravelBuddy is writing your itinerary...'; });
        
        // Pass the Python NSGA-II data to Gemini to make it beautiful
        final aiDescription = await GeminiService.generateTravelPlanDescription(data, widget.requestData);
        data['ai_description'] = aiDescription; // Attach it to the data payload

        if (!mounted) return;
        
        // Navigate to the Final Plan Page and pass the real optimized data + AI text
        Navigator.pushReplacement(
          context,
          MaterialPageRoute(builder: (context) => FinalPlanPage(routeData: data)),
        );
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(
            content: Text('Route Generated by TravelBuddy AI!'),
            backgroundColor: Colors.green,
            behavior: SnackBarBehavior.floating,
          ),
        );
      } else {
        throw Exception('Server returned ${response.statusCode}');
      }
    } catch (e) {
      if (!mounted) return;
      // Fallback if server is not running
      Navigator.pop(context);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Error connecting to backend: $e\nEnsure Python server is running.'),
          backgroundColor: Colors.red,
          behavior: SnackBarBehavior.floating,
        ),
      );
    }
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: const Color(0xFFFFF3E0), // Creamy background
      body: Center(
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            // Animated Logo/Icon
            ScaleTransition(
              scale: _scaleAnimation,
              child: Container(
                width: 140, // Fixed width for perfect circle
                height: 140, // Fixed height for perfect circle
                padding: const EdgeInsets.all(15), // Reduced padding so image fits well
                decoration: BoxDecoration(
                  color: Colors.white,
                  shape: BoxShape.circle,
                  boxShadow: [
                    BoxShadow(
                      color: Colors.black.withValues(alpha: 0.05),
                      blurRadius: 20,
                      offset: const Offset(0, 10),
                    ),
                  ],
                ),
                child: ClipOval(
                  child: Image.network(
                    'https://encrypted-tbn0.gstatic.com/images?q=tbn:ANd9GcRQjoOwAoSmEIRQCvOG3_xQjnUx6GhnSntPHANOU6FYjL4z9nBNKIkmwV0&s', // The new Travel logo
                    fit: BoxFit.contain, // Contain ensures the whole logo is visible
                    errorBuilder: (context, error, stackTrace) => const Icon(
                      Icons.luggage_rounded,
                      color: Color(0xFFE65100),
                      size: 80,
                    ),
                  ),
                ),
              ),
            ),
            
            const SizedBox(height: 50),
            
            // Loading Text
            Text(
              'Curating Your Journey',
              style: GoogleFonts.exo(
                fontSize: 24,
                fontWeight: FontWeight.bold,
                color: const Color(0xFF5D4037),
              ),
            ),
            
            const SizedBox(height: 15),
            
            // Animated sub-messages
            FadeTransition(
              opacity: _fadeAnimation,
              child: Text(
                _currentMessage,
                style: GoogleFonts.exo(
                  fontSize: 15,
                  color: Colors.grey.shade600,
                  fontStyle: FontStyle.italic,
                ),
                textAlign: TextAlign.center,
              ),
            ),
            
            const SizedBox(height: 50),
            
            // Custom Loading Indicator
            const CircularProgressIndicator(
              valueColor: AlwaysStoppedAnimation<Color>(Color(0xFFE65100)),
              strokeWidth: 3,
            ),
          ],
        ),
      ),
    );
  }
}
